# Маппинг визуально схожих символов (гомоглифов) для защиты от подмены букв в спаме и индексах моделей
_LAT_TO_CYR_UPPER = str.maketrans("ABCEHKMOPTXYabcekmoptxy", "АВСЕНКМОРТХУавсекмортху")
_LAT_TO_CYR_LOWER = str.maketrans("abcekmoptxy", "авсекмортху")
_CYR_TO_LAT_MAP = str.maketrans(
    "АВСЕНКМОРТУХІавсекмортхуіЁё",
    "ABCEHKMOPTYXIabcekmoptxyiEe",
)


def dehomoglyph_ru(text: str) -> str:
    """Приводит смешанные кириллическо-латинские слова (Цeна aктуальна) к чистой кириллице."""
    if not text:
        return ""
    # Сначала преобразуем заглавные двойники (H->Н, B->В и др.), затем нижний регистр
    step1 = text.translate(_LAT_TO_CYR_UPPER)
    return step1.lower().replace("ё", "е").translate(_LAT_TO_CYR_LOWER)


def dehomoglyph_lat(text: str) -> str:
    """Нормализует кириллические двойники (Ryzеn 5 7640НS -> ryzen 5 7640hs) внутри латинских/цифровых токенов."""
    if not text:
        return ""

    def _conv_tok(m: re.Match) -> str:
        tok = m.group(0)
        if re.search(r"[A-Za-z0-9]", tok):
            return tok.translate(_CYR_TO_LAT_MAP)
        return tok

    return re.sub(r"[A-Za-zА-Яа-яЁё0-9\-]+", _conv_tok, text).lower()


# 0. ОТСЕВ РЕКЛАМЫ / МАГАЗИННЫХ ЗАМАНУХ / ОПЛАТЫ НАЛИЧНЫМИ (действует всегда, включая тексты с гомоглифами)
